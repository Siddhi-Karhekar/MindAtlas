// Checks that one question never hands over the answer to another, or to
// itself, in a test built by the rule-based generator (no API key):
//   - no sentence is used for two questions: an MCQ blanking "apart from
//     _____" in "A semaphore is an integer variable that, apart from
//     initialization, ..." would print the model answer to "Explain
//     semaphore" beside it;
//   - "a" / "an" before the blank doesn't say whether the answer starts with
//     a vowel;
//   - plural distractors are plurals the notes actually use, not invented
//     words ("framings", "encryptions");
//   - the topic label shown beside an MCQ during an attempt doesn't name its
//     answer ("A _____ is a high level abstraction ..." under "› Monitors").
// No server, no files, no network.
delete process.env.GROQ_API_KEY;

const { blocksFromPlainText, normalizeContent } = await import("../src/services/documentStructure.js");
const { generateQuestions, topicRevealsAnswer } = await import("../src/services/testEngine.js");
const { computeTfidf } = await import("../src/services/tfidf.js");

let failures = 0;
const check = (label, cond, detail = "") => {
  console.log(`${cond ? "  PASS" : "  FAIL"}  ${label}${detail ? "  -> " + String(detail).replace(/\s+/g, " ").slice(0, 200) : ""}`);
  if (!cond) failures++;
};

// verify/fixtures/content.py, Operating Systems - Unit 3 (a subset)
const SECTIONS = {
  "Race Conditions": "A race condition occurs when several processes access and manipulate shared data concurrently and the outcome of the execution depends on the particular order in which the access takes place. To guard against race conditions, we need to ensure that only one process at a time can manipulate the shared variable, which requires that the processes be synchronized in some way. Race conditions are notoriously hard to reproduce because they depend on timing and scheduling decisions made by the kernel.",
  "The Critical Section Problem": "Each process has a segment of code, called a critical section, in which the process may be changing common variables, updating a table or writing a file. A solution to the critical section problem must satisfy three requirements: mutual exclusion, progress and bounded waiting. Mutual exclusion means that if one process is executing in its critical section, then no other process can be executing in its critical section. Bounded waiting limits how many times other processes may enter their critical sections after a process has made a request.",
  Semaphores: "A semaphore is an integer variable that, apart from initialization, is accessed only through two standard atomic operations: wait and signal. A counting semaphore can range over an unrestricted domain, while a binary semaphore can range only between zero and one and behaves like a mutex lock. Semaphores can be implemented without busy waiting by placing a blocked process in a waiting queue associated with the semaphore and waking it with a signal operation.",
  Monitors: "A monitor is a high level abstraction that provides a convenient and effective mechanism for process synchronization. Only one process may be active within the monitor at a time, so the programmer does not need to code this synchronization constraint explicitly. Condition variables inside a monitor allow a process to wait until a particular condition becomes true, using the wait and signal operations on that condition.",
  "Necessary Conditions": "A deadlock is a situation in which every process in a set is waiting for an event that can be caused only by another process in the set. Four conditions must hold simultaneously for a deadlock to occur: mutual exclusion, hold and wait, no preemption and circular wait. A resource allocation graph can be used to describe deadlocks precisely: if the graph contains no cycle, then no process in the system is deadlocked.",
  "Deadlock Prevention": "Deadlock prevention provides a set of methods to ensure that at least one of the necessary conditions cannot hold. For example, the hold and wait condition can be broken by requiring each process to request and be allocated all its resources before it begins execution. The circular wait condition can be broken by imposing a total ordering of all resource types and requiring that each process requests resources in increasing order of enumeration.",
  Paging: "Paging is a memory management scheme that permits the physical address space of a process to be noncontiguous. Physical memory is broken into fixed sized blocks called frames and logical memory into blocks of the same size called pages. Every address generated by the CPU is divided into a page number and a page offset; the page number is used as an index into a page table. A translation lookaside buffer caches recent page table entries to speed up address translation.",
  "Demand Paging": "Virtual memory is a technique that allows the execution of processes that are not completely in memory. With demand paging, pages are loaded only when they are demanded during program execution, so pages that are never accessed are never loaded into physical memory. When a process tries to access a page that is not in memory, a page fault trap occurs and the operating system brings the desired page into a free frame.",
};
const texts = Object.values(SECTIONS);
const corpus = texts.join("\n");
const notes = Object.entries(SECTIONS).map(([title, rawText], i) => ({
  _id: `n${i}`,
  title,
  rawText,
  content: normalizeContent(blocksFromPlainText(rawText), { title }),
  keywords: computeTfidf(rawText, texts.filter((t) => t !== rawText)).keywords,
  path: [],
  parentNoteId: "doc",
  topicLabel: `Operating Systems - Unit 3 › ${title}`,
}));

const sentencesOf = (excerpt) =>
  String(excerpt || "")
    .split(/(?<=[.!?;])\s+/)
    .map((s) => s.toLowerCase().replace(/\s+/g, " ").trim())
    .filter(Boolean);

// options are shuffled, so a few builds rather than one
for (let run = 1; run <= 3; run++) {
  console.log(`\n=== Build ${run} ===`);
  const { accepted } = await generateQuestions(notes, { mcqCount: 12, theoryCount: 6, marksPerQuestion: 1 });
  const mcqs = accepted.filter((q) => q.type === "mcq");

  const owner = new Map();
  let clash = null;
  for (const q of accepted) {
    for (const s of sentencesOf(q.supportingExcerpt)) {
      if (owner.has(s) && owner.get(s) !== q) clash = clash || `${owner.get(s).prompt.slice(0, 60)} / ${q.prompt.slice(0, 60)}`;
      owner.set(s, q);
    }
  }
  check("no sentence is used for two questions", !clash, clash);
  check("the test still has a full pool", mcqs.length >= 10 && accepted.length - mcqs.length >= 5, `${mcqs.length} mcq, ${accepted.length - mcqs.length} theory`);

  const tell = mcqs.find((q) => /\b(?:a|an)\s+_____/i.test(q.prompt));
  check("'a' / 'an' before the blank doesn't hint at the answer", !tell, tell?.prompt);

  const inNotes = (w) => new RegExp(`(?<![A-Za-z])${w}(?![A-Za-z])`, "i").test(corpus);
  const invented = mcqs
    .flatMap((q) => q.options.filter((o) => o !== q.answerKey))
    .find((o) => /^[a-z]+s$/.test(o) && !inNotes(o));
  check("plural distractors are words the notes use", !invented, invented);

  const mixed = mcqs.find((q) => new Set(q.options.map((o) => /\d/.test(o))).size > 1);
  check("numbers are never mixed with words in one question's options", !mixed, mixed && `${mixed.prompt.slice(0, 60)} ${mixed.options}`);
}

console.log("\n=== Topic label during an attempt ===");
check("'Unit 3 › Monitors' gives away 'monitor'", topicRevealsAnswer("Unit 3 › Monitors", "monitor"));
check("'The Critical Section Problem' gives away 'critical section problem'", topicRevealsAnswer("Unit 3 › The Critical Section Problem", "critical section problem"));
check("'Race Conditions' gives away 'race conditions'", topicRevealsAnswer("Unit 3 › Race Conditions", "race conditions"));
check("'Unit 3 › Paging' doesn't give away 'semaphore'", !topicRevealsAnswer("Unit 3 › Paging", "semaphore"));
check("only the subtopic counts, not the document title", !topicRevealsAnswer("Paging Unit › Semaphores", "paging"));

console.log(failures ? `\n${failures} FAILING CHECK(S)` : "\nAll checks passed.");
process.exit(failures ? 1 : 0);
